_VOCAB_INDEX = {w: i for i, w in enumerate(VOCAB)}
_TOKEN_RE = re.compile(r"(?u)\b\w\w+\b")


class Model(nn.Module):
    def __init__(self) -> None:
        super().__init__()
        n = len(VOCAB)
        self.register_buffer("idf", torch.zeros(n))
        self.linear = nn.Linear(n, 1)

    def eval(self) -> "Model":
        super().eval()
        return self

    def _vectorize(self, text: str) -> torch.Tensor:
        tf = torch.zeros(len(VOCAB))
        for tok in _TOKEN_RE.findall(text.lower()):
            idx = _VOCAB_INDEX.get(tok)
            if idx is not None:
                tf[idx] += 1.0
        tfidf = tf * self.idf
        norm = torch.linalg.norm(tfidf)
        if norm > 0:
            tfidf = tfidf / norm
        return tfidf

    def predict(self, batch: Iterable[Any]) -> List[str]:
        out: List[str] = []
        with torch.no_grad():
            for text in batch:
                v = self._vectorize(str(text))
                logit = self.linear(v).item()
                out.append("FoxNews" if logit >= 0.0 else "NBC")
        return out


def get_model() -> Model:
    return Model()
